#!/usr/bin/env node
/**
 * One-time data migration: Supabase → Cloudflare D1 (plan §5).
 *
 * 1. Reads every table (news, events, gallery, site_content) from the
 *    Supabase REST API with the service-role key — run this locally only,
 *    never deploy the service key anywhere.
 * 2. Emits `scripts/d1-import.sql` with idempotent SQLite inserts
 *    (`insert or replace`; ids are preserved so /register?event=<id> links
 *    keep working). No explicit transaction: D1 rejects `BEGIN TRANSACTION`
 *    ("use state.storage.transaction() instead"), so atomicity comes from
 *    `insert or replace` being safe to re-run instead.
 * 3. Prints the exact `wrangler d1 execute` commands to run next.
 *
 * Usage:
 *   SUPABASE_URL=https://<proj>.supabase.co \
 *   SUPABASE_SERVICE_ROLE_KEY=eyJ... \
 *   node scripts/export-supabase-to-d1.mjs
 */

import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const SUPABASE_URL = process.env.SUPABASE_URL ?? process.env.NEXT_PUBLIC_SUPABASE_URL;
const SERVICE_KEY =
  process.env.SUPABASE_SERVICE_ROLE_KEY ?? process.env.SUPABASE_SERVICE_KEY;

if (!SUPABASE_URL || !SERVICE_KEY) {
  console.error(
    "Missing credentials. Run with:\n" +
      "  SUPABASE_URL=https://<proj>.supabase.co \\\n" +
      "  SUPABASE_SERVICE_ROLE_KEY=eyJ... \\\n" +
      "  node scripts/export-supabase-to-d1.mjs\n" +
      "(Supabase → Project Settings → API → service_role key; local use only)",
  );
  process.exit(1);
}

const TABLES = [
  { name: "news", order: "published_at" },
  { name: "events", order: "created_at" },
  { name: "gallery", order: "created_at" },
  { name: "site_content", order: "key" },
];

/** Pull every row of a table (service role bypasses RLS; still paginate). */
async function fetchTable(name) {
  const rows = [];
  const pageSize = 1000;
  let offset = 0;
  for (;;) {
    const response = await fetch(
      `${SUPABASE_URL}/rest/v1/${name}?select=*&limit=${pageSize}&offset=${offset}`,
      {
        headers: {
          apikey: SERVICE_KEY,
          authorization: `Bearer ${SERVICE_KEY}`,
        },
      },
    );
    if (!response.ok) {
      throw new Error(`${name}: HTTP ${response.status} — ${await response.text()}`);
    }
    const page = await response.json();
    rows.push(...page);
    if (page.length < pageSize) return rows;
    offset += pageSize;
  }
}

/** SQLite string literal (single quotes doubled, no NUL bytes). */
function sqlString(value) {
  if (value === null || value === undefined) return "null";
  return `'${String(value).replace(/'/g, "''")}'`;
}

function insertFor(table, row) {
  const columns = Object.keys(row);
  const values = columns.map((c) => sqlString(row[c]));
  return `insert or replace into ${table} (${columns.join(", ")}) values (${values.join(", ")});`;
}

const outPath = join(dirname(fileURLToPath(import.meta.url)), "d1-import.sql");
const lines = [
  "-- Generated by scripts/export-supabase-to-d1.mjs — do not edit by hand.",
  `-- Source: ${SUPABASE_URL}`,
  `-- Generated: ${new Date().toISOString()}`,
  "-- Apply with: npx wrangler d1 execute hope-db --remote --file scripts/d1-import.sql",
  "-- (or add --local to load a dev database). Safe to re-run: insert or replace.",
  "",
];

let total = 0;
for (const { name, order } of TABLES) {
  const rows = await fetchTable(name);
  lines.push(`\n-- ---------- ${name} (${rows.length} rows) ----------`);
  for (const row of rows.sort((a, b) =>
    String(a[order] ?? "").localeCompare(String(b[order] ?? "")),
  )) {
    if (Object.keys(row).length === 0) continue;
    lines.push(insertFor(name, row));
    total += 1;
  }
}

lines.push("");

writeFileSync(outPath, lines.join("\n"));
console.log(`Wrote ${total} rows across ${TABLES.length} tables to ${outPath}`);
console.log("\nNext steps:");
console.log("  1. npx wrangler d1 execute hope-db --remote --file scripts/d1-import.sql");
console.log("  2. Deploy: npm run deploy");
console.log("  3. Spot-check the site and /admin, then delete the Supabase project (plan §6).");
